"""
Build data.js from the source Google Sheet (exported as CSV).

The Google Sheet ("WORKING Community Owned Solar Database") is the source of
truth: every project attribute comes from it. The GeoJSON is used ONLY for
coordinates and the geocoded address, matched on each row's own address.

Why: the older GeoJSON-only build used attributes that had been joined onto the
geocoded points by address. Projects sharing an address (e.g. four Grand Valley
Power projects at 845 22 Road) all inherited ONE project's name/size/year, so
14 projects were missing from the map and others appeared twice.

Usage:
    python build_data_from_sheet.py ["COS Database - Source Sheet.csv"] ["5.3 Project Locations.geojson"] [data.js]
"""

import csv
import json
import re
import sys

from convert_geojson_to_js import clean_text, parse_year, determine_utility_type, size_category

HELPERS_JS = '''\
// Helper: display name for utility type code
function getUtilityTypeName(type) {
    const names = {
        'cooperative':    'Electric Cooperative',
        'investor-owned': 'Investor-Owned Utility',
        'municipal':      'Municipal Utility',
        'consumer-owned': 'Consumer-Owned Utility',
        'other':          'Other',
    };
    return names[type] || type;
}

// Helper: marker color for utility type
function getMarkerColor(type) {
    const colors = {
        'cooperative':    '#10b981',  // green
        'investor-owned': '#3b82f6',  // blue
        'municipal':      '#f59e0b',  // amber
        'consumer-owned': '#8b5cf6',  // purple
        'other':          '#6b7280',  // gray
    };
    return colors[type] || '#6b7280';
}
'''


def norm_address(s):
    return re.sub(r'[^a-z0-9]+', ' ', str(s or '').lower()).strip()


def fix_mojibake(text):
    """Undo UTF-8 text that was decoded as Windows-1252 (possibly twice),
    e.g. "YECÃ¢â‚¬â„¢s" -> "YEC’s". Leaves normal text untouched."""
    for _ in range(3):
        if not re.search('[ÃÂâ€]', text):
            break
        try:
            fixed = text.encode('cp1252').decode('utf-8')
        except (UnicodeEncodeError, UnicodeDecodeError):
            break
        if fixed == text:
            break
        text = fixed
    return text


def to_float(v):
    try:
        return float(str(v).replace(',', ''))
    except (TypeError, ValueError):
        return None


def format_utility_id(v):
    f = to_float(v)
    return f'{int(f):,}' if f is not None else clean_text(v)


def build(csv_path, geojson_path, output_path):
    with open(geojson_path, encoding='utf-8') as f:
        features = json.load(f)['features']
    locations = {}
    for feat in features:
        p = feat['properties']
        lng, lat = feat['geometry']['coordinates'][:2]
        locations.setdefault(norm_address(p.get('original_address')),
                             {'lat': lat, 'lng': lng, 'formatted': p.get('formatted')})

    with open(csv_path, encoding='utf-8', newline='') as f:
        rows = [r for r in csv.DictReader(f) if (r.get('Project Name') or '').strip()]

    projects, missing = [], []
    for idx, r in enumerate(rows, start=1):
        loc = locations.get(norm_address(r['Address']))
        if loc is None:
            missing.append(f"{r['Project Name']} — {r['Address']}")
            continue

        name = fix_mojibake(clean_text(r['Project Name']))
        city = clean_text(r['City'])
        state = clean_text(r['State'])
        utility_type = clean_text(r['Utility Type'])
        basic_struct = clean_text(r['Basic Structure'])
        size_ac = to_float(r['System Size (MW-AC)'])
        size_dc = to_float(r['System Size (MW-DC)'])
        year = parse_year(r['Year of Interconnection'])

        projects.append({
            'id': idx,
            'name': name,
            'location': f'{city}, {state}' if city != 'Unknown' else state,
            'city': city,
            'state': state,
            'lat': loc['lat'],
            'lng': loc['lng'],
            'address': clean_text(loc['formatted'] or r['Address']),
            'utilityType': determine_utility_type(utility_type, basic_struct),
            'utilityTypeName': utility_type if utility_type != 'Unknown' else '',
            'basicStructure': basic_struct if basic_struct != 'Unknown' else '',
            'utility': clean_text(r['Utility']),
            'utilityId': format_utility_id(r['UtilityID']),
            'sizeMwAc': size_ac,
            'sizeMwDc': size_dc,
            'sizeCategory': size_category(size_ac),
            'yearOfInterconnection': year,
            'status': f'Interconnected {year}' if year else 'Unknown',
        })

    if missing:
        sys.exit('No coordinates in the GeoJSON for these rows (geocode them first):\n  '
                 + '\n  '.join(missing))

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('// Community solar project data — auto-generated by build_data_from_sheet.py\n')
        f.write('// Source: WORKING Community Owned Solar Database (Google Sheet); coordinates from GeoJSON\n\n')
        f.write('const communitySolarProjects = ')
        f.write(json.dumps(projects, indent=2, ensure_ascii=False))
        f.write(';\n\n')
        f.write(HELPERS_JS)

    print(f'Built {len(projects)} projects -> {output_path}')


if __name__ == '__main__':
    build(sys.argv[1] if len(sys.argv) > 1 else 'COS Database - Source Sheet.csv',
          sys.argv[2] if len(sys.argv) > 2 else '5.3 Project Locations.geojson',
          sys.argv[3] if len(sys.argv) > 3 else 'data.js')
